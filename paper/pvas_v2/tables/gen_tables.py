#!/usr/bin/env python
"""Generate booktabs .tex table fragments for the PVAS WACV 2027 paper.

Reads ONLY production result JSONs under outputs/ (provenance [R-LOCAL],
tagged \\RLOCAL in the fragments). If an input JSON is missing the table is
still emitted with \\PENDING cells and a warning is printed -- this script
must never crash on partial inputs.

NO numeric literals: every number in the emitted tables is read from a JSON
produced by poc_natural/run_cifar.py, poc_natural/calibration.py, or
scripts/reconstruct_mc.py. The single documented exception: the trajectory
multipliers of CITED ensemble methods in nfe_cost.tex (ADS Np, AdaSense s),
which come from the cited papers, are tagged \\CITED, and are collected in
CITED_FACTORS below with their sources.

Outputs (into this directory):
  sr_main.tex, sr_budget.tex, gate_ablation.tex, inpaint_main.tex,
  mri_main.tex, mri80.tex, nfe_cost.tex
"""
from __future__ import annotations

import json
import math
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]                       # .../fastmri
OUT_DIR = HERE

PENDING = r"\PENDING"
MISSING: list[str] = []
STATUS: dict[str, str] = {}                  # table file -> populated/partial/PENDING


# --------------------------------------------------------------------------
# [CITED] trajectory multipliers for the NFE-cost table ONLY (never used for
# any reconstruction-quality number). Sources verified in docs/lit_review.md:
#   - ADS runs Np = 16 parallel DPS particles => 16x denoiser NFE per step
#     [CITED nolan2025ads, TMLR 2025, arXiv:2406.14388].
#   - AdaSense draws s complete DDRM posterior-sampling runs per acquisition
#     round, e.g. 256 trajectories/image for faces
#     [CITED elata2024adasense, ECCV 2024, arXiv:2407.08256].
# Rows built from these are tagged \CITED and cite the paper.
# --------------------------------------------------------------------------
CITED_FACTORS = {
    "ads_np": 16,          # \cite{nolan2025ads}
    "adasense_runs": 256,  # \cite{elata2024adasense}
}


# ---------------------------------------------------------------- loading --
def load(rel: str) -> dict | None:
    """Load outputs/<rel>/results.json; record and tolerate missing files."""
    p = REPO / "outputs" / rel / "results.json"
    if not p.exists():
        MISSING.append(str(p))
        return None
    try:
        with open(p) as f:
            return json.load(f)
    except Exception as e:  # unreadable / truncated (grid may still be writing)
        MISSING.append(f"{p} (unreadable: {e})")
        return None


# ------------------------------------------------------------- formatting --
def fmt_ms(mean: float | None, std: float | None, prec: int = 2) -> str:
    if mean is None:
        return PENDING
    if std is None:
        return f"{mean:.{prec}f}"
    return f"{mean:.{prec}f}\\,$\\pm$\\,{std:.{prec}f}"


def fmt_delta(mean: float, std: float, prec: int = 2) -> str:
    # math-wrapped so the sign typesets as a real minus, not a hyphen
    return f"${mean:+.{prec}f}$\\,$\\pm$\\,${std:.{prec}f}$"


def fmt_p(p: float | None) -> str:
    if p is None or (isinstance(p, float) and math.isnan(p)):
        return "--"
    if p >= 1e-3:
        return f"$p{{=}}{p:.3f}$"
    if p <= 0.0:
        return "$p{<}10^{-300}$"
    e = int(math.floor(math.log10(p)))
    m = p / (10 ** e)
    return f"$p{{=}}{m:.1f}{{\\times}}10^{{{e}}}$"


def fmt_int(x: float | None) -> str:
    return PENDING if x is None else f"{x:,.0f}".replace(",", "\\,")


def bold(cell: str) -> str:
    return r"\textbf{" + cell + "}"


def write_table(fname: str, lines: list[str], status: str) -> None:
    path = OUT_DIR / fname
    # Layout guard: hand-edited files (paired table* fragments, moved groups)
    # carry a "[length-edit]" marker. Never clobber them; write .new instead
    # so the numbers can be merged by hand.
    if path.exists() and "[length-edit]" in path.read_text():
        path = path.with_suffix(".tex.new")
        status += "; LAYOUT-GUARDED -> wrote .new, merge by hand"
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    STATUS[fname] = status
    print(f"  wrote {path.name:26s} [{status}]")


def header_comment(inputs: list[str]) -> list[str]:
    out = ["% Auto-generated by paper/pvas_v2/tables/gen_tables.py -- do not edit."]
    for rel in inputs:
        p = REPO / "outputs" / rel / "results.json"
        tag = "[R-LOCAL]" if p.exists() else "[MISSING -> \\PENDING]"
        out.append(f"% input: outputs/{rel}/results.json {tag}")
    return out


# ============================================================== CIFAR ======
CIFAR_ORDER = ["static", "random", "raster", "pv", "duo", "oracle", "ensemble", "ens_random"]
CIFAR_REFERENCE = {"oracle", "ensemble", "ens_random"}  # never bolded
CIFAR_DEFAULT_ROWS = ["static", "random", "pv", "oracle", "ensemble", "ens_random"]


def cifar_policy_name(pol: str, cfg: dict | None) -> str:
    k = cfg.get("ensemble_k") if cfg else None
    kstr = f"{k}" if k is not None else "K"
    names = {
        "static": "Static mask (random, up-front)",
        "random": "Random (mid-trajectory)",
        "raster": "Raster (mid-trajectory)",
        "pv": r"\pvas{} (ours)",
        "duo": r"\pvas-duo (ours, 2 traj.)",
        "oracle": r"Oracle error (upper bound)",
        "ensemble": rf"Ensemble-${kstr}$ variance (ref.)",
        "ens_random": rf"Ensemble-${kstr}$, random select (ref.)",
    }
    return names.get(pol, pol.replace("_", r"\_"))


def cifar_main_table(dirname: str, fname: str, label: str, task_phrase: str,
                     inpaint_note: bool = False, dataset: str = "CIFAR-10",
                     merge_dir: str | None = None) -> None:
    d = load(f"poc_natural/{dirname}")
    inputs = [f"poc_natural/{dirname}"]
    if merge_dir is not None:
        d_extra = load(f"poc_natural/{merge_dir}")
        if d is not None and d_extra is not None:
            for blk in ("summary", "per_image", "nfe"):
                for k, v in d_extra.get(blk, {}).items():
                    d[blk].setdefault(k, v)
            inputs.append(f"poc_natural/{merge_dir}")
    lines = header_comment(inputs)

    if d is None:
        cfg, summary = None, {}
        rows = CIFAR_DEFAULT_ROWS
        n_str = PENDING
        cap_cfg = ""
    else:
        cfg = d.get("config", {})
        summary = d.get("summary", {})
        rows = [p for p in CIFAR_ORDER if p in summary]
        n_str = str(cfg.get("n_images", PENDING))
        cap_cfg = (f", $L{{=}}{cfg.get('budget_blocks')}$ blocks of "
                   f"{cfg.get('block')}$\\times${cfg.get('block')} px, "
                   f"$T{{=}}{cfg.get('num_steps')}$ steps, "
                   f"$\\sigma_y{{=}}{cfg.get('sigma_y')}$")

    lines.append(f"% n = {n_str} images (from JSON config); seed = "
                 f"{cfg.get('seed') if cfg else PENDING}")

    # 29b: the inpainting table must state the harder observation model:
    # unlike SR, no low-resolution preview is ever observed (run_cifar.py
    # init_block_state with_lr=False), so reconstruction starts from scratch
    # conditioned only on the initial random block fraction (frac0, read from
    # the JSON config) plus the acquired blocks.
    note = ""
    if inpaint_note:
        frac0 = cfg.get("frac0") if cfg else None
        f_str = f"{frac0:g}" if frac0 is not None else PENDING
        note = (r" Unlike the SR task, no low-resolution preview is observed:"
                r" reconstruction proceeds from scratch, conditioned only on"
                rf" the initial random fraction ({f_str}) of blocks plus the"
                r" acquired blocks.")

    lines += [
        r"\begin{table}[t]",
        r"  \centering\small",
        r"  \setlength{\tabcolsep}{4pt}",
        rf"  \caption{{{task_phrase} on {dataset} at matched measurement budget"
        rf"{cap_cfg}; $n{{=}}{n_str}$ images\RLOCAL.{note} Oracle and ensemble rows are"
        r" references and excluded from bolding. $\Delta$ rows are paired"
        r" per-image \psnrm{} differences with one-sided Wilcoxon $p$.}",
        rf"  \label{{{label}}}",
        r"  \begin{tabular}{lccc}",
        r"    \toprule",
        r"    Acquisition policy & \psnrm{} (dB) & \ssimm{} & \nfe/image \\",
        r"    \midrule",
    ]

    # bold targets among non-reference rows
    best_psnr = best_ssim = None
    if d is not None:
        cand = [p for p in rows if p not in CIFAR_REFERENCE]
        if cand:
            best_psnr = max(cand, key=lambda p: summary[p]["psnr_mean"])
            best_ssim = max(cand, key=lambda p: summary[p]["ssim_mean"])

    for pol in rows:
        name = cifar_policy_name(pol, cfg)
        if d is None:
            lines.append(f"    {name} & {PENDING} & {PENDING} & {PENDING} \\\\")
            continue
        s = summary[pol]
        c_psnr = fmt_ms(s["psnr_mean"], s["psnr_std"], 2)
        c_ssim = fmt_ms(s["ssim_mean"], s["ssim_std"], 3)
        if pol == best_psnr:
            c_psnr = bold(c_psnr)
        if pol == best_ssim:
            c_ssim = bold(c_ssim)
        lines.append(f"    {name} & {c_psnr} & {c_ssim} & "
                     f"{fmt_int(s.get('nfe_per_image'))} \\\\")

    # paired delta rows (present in JSON summary as delta_pv_vs_<ref>)
    delta_refs = ([r for r in ["static", "random", "raster", "duo", "ensemble", "oracle"]
                   if d is not None and f"delta_pv_vs_{r}" in summary]
                  if d is not None else [])
    if d is None or delta_refs:
        lines.append(r"    \midrule")
        lines.append(r"    \multicolumn{4}{l}{\emph{Paired $\Delta$\psnrm{} "
                     r"(\pvas{} $-$ baseline), dB}} \\")
    if d is None:
        lines.append(f"    $\\Delta$ vs.\\ static & {PENDING} & {PENDING} & \\\\")
        lines.append(f"    $\\Delta$ vs.\\ random & {PENDING} & {PENDING} & \\\\")
    else:
        for ref in delta_refs:
            dd = summary[f"delta_pv_vs_{ref}"]
            lines.append(
                f"    $\\Delta$ vs.\\ {ref.replace('_', ' ')} & "
                f"{fmt_delta(dd['mean'], dd['std'])} & "
                f"{fmt_p(dd.get('wilcoxon_p_greater'))} & \\\\")

    lines += [r"    \bottomrule", r"  \end{tabular}", r"\end{table}"]
    write_table(fname, lines, "populated" if d is not None else "PENDING")


# Budget row labels when a run's JSON is missing. For cifar_sr_b<L> runs the
# label comes from the directory-name convention; cifar_sr_main does not carry
# its budget in its name, so its label (the L=12 production configuration of
# poc_natural/run_cifar.py, a config parameter -- NOT a result number) is
# recorded here. When the JSON is present the label is always read from it.
BUDGET_LABEL_FALLBACK = {"cifar_sr_main": "12"}


def sr_budget_table() -> None:
    specs = ["cifar_sr_b6", "cifar_sr_main", "cifar_sr_b18", "cifar_sr_b24"]
    data = {name: load(f"poc_natural/{name}") for name in specs}
    lines = ["% supplement candidate -- not \\input by the main paper;"
             " kept generated for the supplement (with fig_nfe_cost.pdf)."]
    lines += header_comment([f"poc_natural/{n}" for n in specs])

    pols = ["static", "random", "pv", "oracle"]
    n_vals = sorted({d["config"].get("n_images") for d in data.values() if d})
    n_str = "/".join(str(v) for v in n_vals) if n_vals else PENDING
    lines.append(f"% n = {n_str} images per budget point (from JSON configs)")
    lines += [
        r"\begin{table}[t]",
        r"  \centering\small",
        r"  \setlength{\tabcolsep}{4pt}",
        rf"  \caption{{\psnrm{{}} (dB) vs.\ acquisition budget $L$ (blocks) on"
        rf" CIFAR-10 adaptive super-resolution, $n{{=}}{n_str}$ images per"
        r" point\RLOCAL. Best non-oracle entry per row in bold; the oracle"
        r" column is a reference. See also Fig.~\ref{fig:budget}.}",
        r"  \label{tab:sr_budget}",
        r"  \begin{tabular}{lcccc}",
        r"    \toprule",
        r"    Budget $L$ & Static & Random & \pvas{} (ours) & Oracle (ref.) \\",
        r"    \midrule",
    ]

    any_loaded = False
    for name in specs:
        d = data[name]
        if d is None:
            m = re.search(r"_b(\d+)$", name)
            lab = m.group(1) if m else BUDGET_LABEL_FALLBACK.get(name, PENDING)
            lines.append("    " + " & ".join([lab] + [PENDING] * len(pols)) + r" \\")
            continue
        any_loaded = True
        cfg, summary = d.get("config", {}), d.get("summary", {})
        lab = str(cfg.get("budget_blocks", PENDING))
        avail = [p for p in pols if p in summary and p != "oracle"]
        best = max(avail, key=lambda p: summary[p]["psnr_mean"]) if avail else None
        cells = []
        for p in pols:
            if p not in summary:
                cells.append(PENDING)
                continue
            c = fmt_ms(summary[p]["psnr_mean"], summary[p]["psnr_std"], 2)
            cells.append(bold(c) if p == best else c)
        lines.append("    " + " & ".join([lab] + cells) + r" \\")

    lines += [r"    \bottomrule", r"  \end{tabular}", r"\end{table}"]
    n_loaded = sum(1 for d in data.values() if d)
    status = ("populated" if n_loaded == len(specs)
              else ("partial" if n_loaded else "PENDING"))
    write_table("sr_budget.tex", lines, status)


def gate_ablation_table() -> None:
    """Gate x acquisition ablation on noisy CIFAR SR (sigma_y > 0).

    Rows come from two runs of run_cifar.py that differ only in --pv_gate;
    the PV gate applies to the 'pv' policy, so the grid is
    {static, random, pv} x {scalar DC, PV-gated DC (pv only)}.
    """
    d_ng = load("poc_natural/cifar_sr_noisy_nogate")
    d_g = load("poc_natural/cifar_sr_noisy_gate")
    lines = header_comment(["poc_natural/cifar_sr_noisy_nogate",
                            "poc_natural/cifar_sr_noisy_gate"])

    cfg = (d_ng or d_g or {}).get("config", {})
    n_str = str(cfg.get("n_images", PENDING))
    sig_str = str(cfg.get("sigma_y", PENDING))
    lines.append(f"% n = {n_str} images; sigma_y = {sig_str} (from JSON config)")
    lines += [
        r"\begin{table}[t]",
        r"  \centering\small",
        r"  \setlength{\tabcolsep}{4pt}",
        rf"  \caption{{Gate$\times$acquisition ablation on noisy CIFAR-10"
        rf" super-resolution ($\sigma_y{{=}}{sig_str}$, $n{{=}}{n_str}$"
        r" images)\RLOCAL: the same PV map used as acquisition score, as"
        r" Kalman gain $\gain_i = \PV_i/(\PV_i+\sigma_i^2)$ for data"
        r" consistency, or both. Best entry per column in bold (reference"
        r" rows excluded). $\Delta$ row: paired per-image \psnrm{}"
        r" difference, one-sided Wilcoxon $p$.}",
        r"  \label{tab:ablation_gate}",
        r"  \begin{tabular}{llccc}",
        r"    \toprule",
        r"    Acquisition & DC gain & \psnrm{} (dB) & \ssimm{} & \nfe/image \\",
        r"    \midrule",
    ]

    # (row label pieces, source json, policy)
    spec = [
        ("Static (up-front)", "scalar", d_ng, "static"),
        ("Random (mid-traj.)", "scalar", d_ng, "random"),
        (r"\textsc{pv} (ours)", "scalar", d_ng, "pv"),
        (r"\textsc{pv} (ours)", r"\textsc{pv}-gated", d_g, "pv"),
    ]
    present = [(a, g, d, p) for (a, g, d, p) in spec
               if d is not None and p in d.get("summary", {})]
    best_psnr = best_ssim = None
    if present:
        best_psnr = max(present, key=lambda r: r[2]["summary"][r[3]]["psnr_mean"])
        best_ssim = max(present, key=lambda r: r[2]["summary"][r[3]]["ssim_mean"])

    for row in spec:
        acq, gate_lab, d, pol = row
        if d is None or pol not in d.get("summary", {}):
            lines.append(f"    {acq} & {gate_lab} & {PENDING} & {PENDING} & "
                         f"{PENDING} \\\\")
            continue
        s = d["summary"][pol]
        c_psnr = fmt_ms(s["psnr_mean"], s["psnr_std"], 2)
        c_ssim = fmt_ms(s["ssim_mean"], s["ssim_std"], 3)
        if row == best_psnr:
            c_psnr = bold(c_psnr)
        if row == best_ssim:
            c_ssim = bold(c_ssim)
        lines.append(f"    {acq} & {gate_lab} & {c_psnr} & {c_ssim} & "
                     f"{fmt_int(s.get('nfe_per_image'))} \\\\")

    # cross-run paired delta: pv(gated) - pv(ungated), same images/seeds.
    lines.append(r"    \midrule")
    delta_cells = f"{PENDING} & {PENDING}"
    if (d_ng is not None and d_g is not None
            and "pv" in d_ng.get("per_image", {})
            and "pv" in d_g.get("per_image", {})
            and d_ng["config"].get("seed") == d_g["config"].get("seed")
            and d_ng["config"].get("n_images") == d_g["config"].get("n_images")):
        try:
            import numpy as np
            from scipy.stats import wilcoxon
            diff = (np.array(d_g["per_image"]["pv"]["psnr"])
                    - np.array(d_ng["per_image"]["pv"]["psnr"]))
            try:
                pval = float(wilcoxon(diff, alternative="greater").pvalue)
            except ValueError:
                pval = float("nan")
            delta_cells = (f"{fmt_delta(float(diff.mean()), float(diff.std()))}"
                           f" & {fmt_p(pval)}")
        except ImportError:
            pass
    lines.append(r"    \multicolumn{2}{l}{$\Delta$(gated $-$ scalar), "
                 r"\textsc{pv} policy} & " + delta_cells + r" & \\")

    lines += [r"    \bottomrule", r"  \end{tabular}", r"\end{table}"]
    n_loaded = sum(1 for d in (d_ng, d_g) if d)
    status = "populated" if n_loaded == 2 else ("partial" if n_loaded else "PENDING")
    write_table("gate_ablation.tex", lines, status)


# ================================================================ MRI ======
MRI_ORDER = ["pigdm_mc", "pv", "static_match", "random_adaptive",
             "equi_adaptive", "energy_active", "pv_active",
             "ens_active", "ens_random_active", "oracle_active"]
MRI_REFERENCE = {"oracle_active", "ens_active", "ens_random_active"}
MRI_DEFAULT_ROWS = ["pigdm_mc", "static_match", "random_adaptive",
                    "pv_active", "ens_active", "oracle_active"]
# Methods that run the PV estimator every step (see run_fakgd_mc_pv in
# src/samplers/multicoil_pv.py: use_pv_gate=True => n_probes Hutchinson
# probes per step, 2 denoiser calls each when pv_centered).
MRI_PV_GATED = {"pv", "pv_active", "random_adaptive", "energy_active",
                "oracle_active", "equi_adaptive"}


def mri_nfe(cfg: dict, method: str) -> float | None:
    """Denoiser calls per slice, derived from the run's own JSON config.

    Gate ON (legacy grids): PV-gated methods probe every step ->
        T * (1 + 2q). Gate OFF (production v2): only pv_active probes, and
        only at the R_a acquisition rounds -> T + 2q*R_a; every other
        single-trajectory method costs T. Ensemble baselines cost N*T.
    """
    T = cfg.get("num_steps")
    if T is None:
        return None
    if method in ("ens_active", "ens_random_active"):
        N = cfg.get("ens_particles", 4)
        return N * T
    gate_on = cfg.get("active_gate", "on") == "on"
    q = cfg.get("pv_n_probes")
    calls = 2 if cfg.get("pv_centered", True) else 1
    if gate_on:
        if method in MRI_PV_GATED:
            return None if q is None else T * (1 + q * calls)
        return T
    # gate off: only pv_active (and the pv gate-only row, which is always
    # gated) pay for probes
    if method == "pv":
        return None if q is None else T * (1 + q * calls)
    if method == "pv_active":
        R_a = cfg.get("active_rounds", 1)
        return None if q is None else T + q * calls * R_a
    return T


def mri_method_name(m: str) -> str:
    names = {
        "pigdm_mc": r"\pigdm{} (passive)",
        "fakgd_mc": r"FA-KGD (passive)",
        "pv": r"+ \textsc{pv} gate (passive)",
        "static_match": "Static, matched budget",
        "random_adaptive": "Random adaptive",
        "equi_adaptive": "Equispaced adaptive",
        "energy_active": "Energy adaptive",
        "pv_active": r"\pvas{} (ours)",
        "ens_active": r"Ensemble-$N$ particles (ADS-style ref.)",
        "ens_random_active": r"Ensemble-$N$, random select (ref.)",
        "oracle_active": "Oracle selection (bound)",
    }
    return names.get(m, m.replace("_", r"\_"))


def parse_grid_name(name: str) -> tuple[str, str]:
    m = re.match(r"R(\d+)_a(\d+)", name)
    return (m.group(1), m.group(2)) if m else (PENDING, PENDING)


def mri_table(root: str, config_names: list[str], fname: str, label: str,
              caption_extra: str) -> None:
    data = {n: load(f"{root}/{n}") for n in config_names}
    lines = header_comment([f"{root}/{n}" for n in config_names])

    any_cfg = next((d["config"] for d in data.values() if d), None)
    ncomment = []
    for name, d in data.items():
        if d:
            ns = {v.get("n") for k, v in d["summary"].items()
                  if not k.startswith("_") and isinstance(v, dict) and "n" in v}
            ncomment.append(f"{name}: n={sorted(ns)}")
        else:
            ncomment.append(f"{name}: n=PENDING")
    lines.append("% slices per config: " + "; ".join(ncomment))

    steps = any_cfg.get("num_steps") if any_cfg else None
    setup = (f", $T{{=}}{steps}$ EDM steps" if steps is not None else "")
    # 25: only claim [R-LOCAL] provenance when at least one config actually
    # loaded; an all-\PENDING table carries no locally measured numbers.
    rlocal = r"\RLOCAL" if any(d is not None for d in data.values()) else ""
    lines += [
        r"\begin{table}[t]",
        r"  \centering\small",
        r"  \setlength{\tabcolsep}{3pt}",
        rf"  \caption{{Multi-coil fastMRI brain k-space line acquisition"
        rf"{caption_extra}{setup}{rlocal}. All adaptive methods receive the"
        r" same total column budget as the static baseline (matched budget);"
        r" SENSE-referenced \psnrm/\ssimm. Best non-oracle entry per group in"
        r" bold. $\Delta$ rows: paired per-slice \psnrm{} differences with"
        r" one-sided Wilcoxon $p$.}",
        rf"  \label{{{label}}}",
        r"  \begin{tabular}{lcccc}",
        r"    \toprule",
        r"    Method & Cols & \psnrm{} (dB) & \ssimm{} & \nfe/slice \\",
    ]

    for name in config_names:
        d = data[name]
        R, L = parse_grid_name(name)
        if d is not None:
            cfg = d["config"]
            R, L = str(cfg.get("acceleration", R)), str(cfg.get("active_lines", L))
        lines.append(r"    \midrule")
        lines.append(rf"    \multicolumn{{5}}{{l}}{{\emph{{$R{{=}}{R}$,"
                     rf" $L{{=}}{L}$ active lines}}}} \\")
        if d is None:
            for m in MRI_DEFAULT_ROWS:
                lines.append(f"    {mri_method_name(m)} & {PENDING} & {PENDING}"
                             f" & {PENDING} & {PENDING} \\\\")
            continue

        cfg, summary = d["config"], d["summary"]
        rows = [m for m in MRI_ORDER if m in summary]
        cand = [m for m in rows if m not in MRI_REFERENCE]
        best_psnr = (max(cand, key=lambda m: summary[m]["psnr_sense_mean"])
                     if cand else None)
        best_ssim = (max(cand, key=lambda m: summary[m]["ssim_sense_mean"])
                     if cand else None)

        for m in rows:
            s = summary[m]
            c_psnr = fmt_ms(s["psnr_sense_mean"], s["psnr_sense_std"], 2)
            c_ssim = fmt_ms(s["ssim_sense_mean"], s["ssim_sense_std"], 3)
            if m == best_psnr:
                c_psnr = bold(c_psnr)
            if m == best_ssim:
                c_ssim = bold(c_ssim)
            lines.append(f"    {mri_method_name(m)} & {s.get('budget_cols', '--')}"
                         f" & {c_psnr} & {c_ssim} & {fmt_int(mri_nfe(cfg, m))} \\\\")

        # paired deltas recorded by reconstruct_mc.py as _<cand>_vs_<ref>
        for key in sorted(summary):
            if not key.startswith("_pv_active_vs_"):
                continue
            ref = key[len("_pv_active_vs_"):]
            dd = summary[key]
            lines.append(
                f"    $\\Delta$(\\pvas{{}} $-$ {ref.replace('_', ' ')}) & "
                f"($n{{=}}{dd.get('n', '--')}$) & "
                f"{fmt_delta(dd['delta_psnr_sense_mean'], dd['delta_psnr_sense_std'])}"
                f" & {fmt_p(dd.get('wilcoxon_p_greater'))} & \\\\")

    lines += [r"    \bottomrule", r"  \end{tabular}", r"\end{table}"]
    n_loaded = sum(1 for d in data.values() if d)
    status = ("populated" if n_loaded == len(config_names)
              else ("partial" if n_loaded else "PENDING"))
    write_table(fname, lines, status)


def mri_full_table() -> None:
    """192-slice production table: pool per-slice metrics across volume chunks."""
    import numpy as _np
    try:
        from scipy.stats import wilcoxon as _wilcoxon
    except Exception:
        _wilcoxon = None
    groups = {"R8_a16": [f"PVAS_full/R8_a16_chunk{c}" for c in (1, 2, 3)],
              "R4_a8": [f"PVAS_full/R4_a8_chunk{c}" for c in (1, 2, 3)]}
    lines = header_comment([g for gs in groups.values() for g in gs])
    lines += [r"\begin{table}[t]", r"  \centering\small",
              r"  \setlength{\tabcolsep}{3pt}"]
    loaded_any = False
    body = []
    for gname, rels in groups.items():
        datas = [load(r) for r in rels]
        datas = [d for d in datas if d]
        R, L = parse_grid_name(gname)
        body.append(r"    \midrule")
        body.append(rf"    \multicolumn{{5}}{{l}}{{\emph{{$R{{=}}{R}$,"
                    rf" $L{{=}}{L}$ active lines}}}} \\")
        if not datas:
            for m in MRI_DEFAULT_ROWS:
                body.append(f"    {mri_method_name(m)} & {PENDING} & {PENDING}"
                            f" & {PENDING} & {PENDING} \\\\")
            continue
        loaded_any = True
        cfg = datas[0]["config"]
        methods = [m for m in MRI_ORDER
                   if all(m in d["summary"] for d in datas)]
        pooled = {}
        for m in methods:
            ps, ss, cols = [], [], None
            for d in datas:
                per = d.get("per_slice", {}).get(m)
                if isinstance(per, list):
                    ps += [x.get("psnr_sense") for x in per if isinstance(x, dict)]
                    ss += [x.get("ssim_sense") for x in per if isinstance(x, dict)]
                cols = d["summary"][m].get("budget_cols", cols)
            ps = [x for x in ps if x is not None]
            ss = [x for x in ss if x is not None]
            pooled[m] = (ps, ss, cols)
        cand = [m for m in methods if m not in MRI_REFERENCE]
        best = (max(cand, key=lambda m: _np.mean(pooled[m][0])) if cand else None)
        for m in methods:
            ps, ss, cols = pooled[m]
            if not ps:
                continue
            c_p = fmt_ms(float(_np.mean(ps)), float(_np.std(ps)), 2)
            c_s = fmt_ms(float(_np.mean(ss)), float(_np.std(ss)), 3) if ss else "--"
            if m == best:
                c_p = bold(c_p)
            body.append(f"    {mri_method_name(m)} & {cols} & {c_p} & {c_s}"
                        f" & {fmt_int(mri_nfe(cfg, m))} \\\\")
        n_pool = len(pooled.get("pv_active", ([],))[0])
        for ref in ("static_match", "random_adaptive", "ens_active"):
            if "pv_active" in pooled and ref in pooled and pooled[ref][0]:
                a = _np.array(pooled["pv_active"][0])
                b = _np.array(pooled[ref][0])
                if len(a) == len(b) and len(a) > 0:
                    dlt = a - b
                    pval = (float(_wilcoxon(dlt, alternative="greater").pvalue)
                            if _wilcoxon is not None and len(dlt) > 1 else None)
                    body.append(
                        f"    $\\Delta$(\\pvas{{}} $-$ {ref.replace('_', ' ')}) &"
                        f" ($n{{=}}{len(dlt)}$) &"
                        f" {fmt_delta(float(dlt.mean()), float(dlt.std()))} &"
                        f" {fmt_p(pval)} & \\\\")
    lines += [
        rf"  \caption{{192-slice production grid (12 AXFLAIR volumes, pooled"
        rf" across chunks){' ' if loaded_any else ''}"
        + (r"\RLOCAL" if loaded_any else "")
        + r". Protocol of Table~\ref{tab:mri_main}.}",
        r"  \label{tab:mri_full}",
        r"  \begin{tabular}{lcccc}", r"    \toprule",
        r"    Method & Cols & \psnrm{} (dB) & \ssimm{} & \nfe/slice \\",
    ] + body + [r"    \bottomrule", r"  \end{tabular}", r"\end{table}"]
    write_table("mri_full.tex", lines,
                "populated" if loaded_any else "PENDING")


