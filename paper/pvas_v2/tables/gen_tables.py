def nfe_cost_table() -> None:
    d_sr = load("poc_natural/cifar_sr_main")
    d_mri = load("PVAS_ng/R8_a16") or load("PVAS_ng/R4_a8")
    lines = header_comment(["poc_natural/cifar_sr_main", "PVAS_ng/R8_a16"])
    lines.append("% CITED multipliers: ADS Np=16 [nolan2025ads]; AdaSense s=256"
                 " posterior runs (faces example) [elata2024adasense].")
    lines.append("% Cited methods are expressed as (their published trajectory"
                 " multiplier) x (our T from the JSON config); marked \\CITED.")

    T_sr = d_sr["config"].get("num_steps") if d_sr else None
    n_sr = d_sr["config"].get("n_images") if d_sr else None
    lines.append(f"% n = {n_sr if n_sr is not None else 'PENDING'} CIFAR images;"
                 " MRI NFE derived per slice from JSON config (see mri_nfe).")

    lines += [
        r"\begin{table}[t]",
        r"  \centering\small",
        r"  \setlength{\tabcolsep}{4pt}",
        r"  \caption{Denoiser calls (\nfe) per reconstructed image for each"
        r" acquisition-capable method. \RLOCAL{} measured in this repo;"
        r" \CITED{} derived from the cited paper's published trajectory"
        r" multiplier at the same trajectory length $T$ as our runs."
        r" The last column is the ratio to the passive single-trajectory"
        r" baseline of the same domain.}",
        r"  \label{tab:nfe_cost}",
        r"  \begin{tabular}{llcc}",
        r"    \toprule",
        r"    Method & Uncertainty source & \nfe/image & vs.\ passive \\",
        r"    \midrule",
    ]

    def ratio(nfe, base):
        if nfe is None or base in (None, 0):
            return PENDING
        return f"$\\times${nfe / base:.1f}"

    # --- CIFAR block acquisition rows (T from cifar_sr_main config) ---
    base_sr = (d_sr["summary"]["static"]["nfe_per_image"]
               if d_sr and "static" in d_sr.get("summary", {}) else None)
    rows: list[tuple[str, str, float | None]] = []
    if d_sr:
        smry = d_sr["summary"]
        k = d_sr["config"].get("ensemble_k", "K")
        if "static" in smry:
            rows.append((r"Passive (static mask)\RLOCAL", "none",
                         smry["static"]["nfe_per_image"]))
        if "pv" in smry:
            rows.append((r"\pvas{} (ours)\RLOCAL",
                         "single-trajectory Tweedie \\textsc{pv}",
                         smry["pv"]["nfe_per_image"]))
        if "ensemble" in smry:
            rows.append((rf"Ensemble-${k}$ selection\RLOCAL",
                         rf"${k}$ posterior trajectories",
                         smry["ensemble"]["nfe_per_image"]))
    else:
        rows += [(r"Passive (static mask)\RLOCAL", "none", None),
                 (r"\pvas{} (ours)\RLOCAL",
                  "single-trajectory Tweedie \\textsc{pv}", None),
                 (r"Ensemble selection\RLOCAL", "posterior trajectories", None)]
    # cited rows at our T (from the same JSON config)
    rows.append((r"ADS\CITED~\cite{nolan2025ads}",
                 f"$N_p{{=}}{CITED_FACTORS['ads_np']}$ DPS particles",
                 CITED_FACTORS["ads_np"] * T_sr if T_sr else None))
    rows.append((r"AdaSense\CITED~\cite{elata2024adasense}",
                 f"$s{{=}}{CITED_FACTORS['adasense_runs']}$ posterior runs",
                 CITED_FACTORS["adasense_runs"] * T_sr if T_sr else None))

    lines.append(r"    \multicolumn{4}{l}{\emph{CIFAR-10 block acquisition"
                 + (f" ($T{{=}}{T_sr}$)" if T_sr else "") + r"}} \\")
    for name, src, nfe in rows:
        lines.append(f"    {name} & {src} & {fmt_int(nfe)} & "
                     f"{ratio(nfe, base_sr)} \\\\")

    # --- MRI line acquisition rows (derived from R4_a8 config) ---
    lines.append(r"    \midrule")
    T_mri = d_mri["config"].get("num_steps") if d_mri else None
    lines.append(r"    \multicolumn{4}{l}{\emph{fastMRI multi-coil line"
                 r" acquisition" + (f" ($T{{=}}{T_mri}$)" if T_mri else "")
                 + r"}} \\")
    if d_mri:
        cfg = d_mri["config"]
        base_mri = mri_nfe(cfg, "pigdm_mc")
        for m in ["pigdm_mc", "static_match", "pv_active"]:
            if m in d_mri.get("summary", {}):
                src = ("single-trajectory Tweedie \\textsc{pv}"
                       if m in MRI_PV_GATED else "none")
                nfe = mri_nfe(cfg, m)
                lines.append(f"    {mri_method_name(m)}\\RLOCAL & {src} & "
                             f"{fmt_int(nfe)} & {ratio(nfe, base_mri)} \\\\")
    else:
        for nm in [r"\pigdm{} (passive)\RLOCAL", r"\pvas{} (ours)\RLOCAL"]:
            lines.append(f"    {nm} & {PENDING} & {PENDING} & {PENDING} \\\\")

    lines += [r"    \bottomrule", r"  \end{tabular}", r"\end{table}"]
    n_loaded = sum(1 for d in (d_sr, d_mri) if d)
    status = "populated" if n_loaded == 2 else ("partial" if n_loaded else "PENDING")
    write_table("nfe_cost.tex", lines, status)


